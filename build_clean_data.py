"""Step 2: turn the raw cache into the clean tables the website reads (no network needed).

    python build_clean_data.py             # every table; needs every shot chart in data/raw/
    python build_clean_data.py --partial   # every table except shot_grid and zone_seasons

Writes data/clean/<table>.csv plus data/clean/README.md: a data dictionary, the cleaning
rules, and the result of every validation check. Re-run it after downloading more data
(e.g. more shot-chart seasons). Exits with an error if any check fails.

--partial is for when the shot charts (the slowest download) are not all in data/raw/: shot_grid.csv
and zone_seasons.csv are kept from the last full build, and the timeline's events read zone_seasons.csv.
"""
import sys

import pandas as pd

from nbaviz import config as C
from nbaviz import export, fetch

CLEAN_DIR = C.CLEAN_DIR


def readme(tables: dict, results: list, partial: bool) -> str:
    lines = ["# Clean data", "",
             "Generated by `python build_clean_data.py` from the raw cache in `data/raw/` (regular season only): "
             "team and league tables from Basketball-Reference "
             f"([Kaggle `{C.BREF_DATASET}`](https://www.kaggle.com/datasets/{C.BREF_DATASET}) v{C.BREF_VERSION}), "
             "shots and players from NBA.com. Do not edit by hand.", ""]
    if partial:
        lines += [f"Partial build: {', '.join(f'`{n}.csv`' for n in export.SHOT_TABLES)} are kept from the last "
                  "full build, not rebuilt from the shot charts.", ""]
    lines += ["## Files", ""]
    for name, (_, about, columns) in export.TABLES.items():
        df = tables[name]
        lines += [f"### `{name}.csv`", "", f"{about} {len(df):,} rows.", "",
                  "| Column | Meaning |", "|---|---|"]
        lines += [f"| `{col}` | {text} |" for col, text in columns.items()]
        lines.append("")
    lines += ["## Cleaning rules", ""] + [f"{i}. {rule}" for i, rule in enumerate(export.CLEANING_RULES, 1)]
    lines += ["", "## Validation checks", "", "| Check | Result | Detail |", "|---|---|---|"]
    lines += [f"| {r['check']} | {r['status']} | {r['detail']} |" for r in results]
    return "\n".join(lines) + "\n"


def main(partial: bool):
    missing = fetch.missing_shot_charts()
    if missing and not partial:
        sys.exit(f"{len(missing)} shot-chart files are not downloaded yet (first: {missing[0]}). "
                 "Run python collect_data.py shots, or python build_clean_data.py --partial "
                 "to rebuild everything else.")

    CLEAN_DIR.mkdir(parents=True, exist_ok=True)
    tables = {}
    for name, (build, _, _) in export.TABLES.items():
        print(f"{name}", end=" ", flush=True)
        path = CLEAN_DIR / f"{name}.csv"
        if partial and name in export.SHOT_TABLES:
            if not path.exists():
                sys.exit(f"\n{path} is missing, so a partial build has nothing to keep. Run a full build.")
            tables[name] = pd.read_csv(path)
            print(f"{len(tables[name]):,} rows, kept")
            continue
        df = (build(tables["zone_seasons"]) if partial and name == "events" else build()).round(4)
        df.to_csv(path, index=False)
        tables[name] = df
        print(f"{len(df):,} rows, {path.stat().st_size / 1e3:,.0f} KB")

    print("\nChecks")
    results = export.checks(tables["shot_grid"] if partial else None)
    for r in results:
        print(f"  [{r['status']}] {r['check']}: {r['detail']}")
    (CLEAN_DIR / "README.md").write_text(readme(tables, results, partial))
    print(f"\nWrote {len(tables)} tables and README.md to {CLEAN_DIR}")
    if any(r["status"] == "FAIL" for r in results):
        sys.exit(1)


if __name__ == "__main__":
    main("--partial" in sys.argv[1:])
