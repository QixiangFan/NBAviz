"""Optional step: every column of the Basketball-Reference tables, linked to NBA.com ids (no network needed).

    python collect_data.py gamelogs players bref   # the raw data this step reads
    python build_interim_data.py

Writes data/interim/<table>.csv plus data/interim/README.md (data dictionary, cleaning rules,
validation checks). data/interim/ is git-ignored and nothing in data/clean/ or on the website reads
it, so this step can be skipped when only rebuilding the site. Exits with an error if any check fails.
"""
import sys

from nbaviz import config as C
from nbaviz import interim

OUT_DIR = C.INTERIM_DIR


def readme(tables: dict, results: list) -> str:
    lines = ["# Interim data", "",
             "Generated by `python build_interim_data.py` from the raw cache in `data/raw/`: Basketball-Reference "
             f"([Kaggle `{C.BREF_DATASET}`](https://www.kaggle.com/datasets/{C.BREF_DATASET}) v{C.BREF_VERSION}) "
             "with NBA.com team and player ids. Not used by the website; git-ignored. "
             "Seasons are starting years (2025 = 2025-26).", "",
             "## Files", ""]
    for name, (_, about, columns) in interim.TABLES.items():
        df = tables[name]
        lines += [f"### `{name}.csv`", "", f"{about} {len(df):,} rows.", "",
                  "| Column | Meaning |", "|---|---|"]
        lines += [f"| `{col}` | {text} |" for col, text in columns.items()]
        lines.append("")
    lines += ["## Cleaning rules", ""] + [f"{i}. {rule}" for i, rule in enumerate(interim.CLEANING_RULES, 1)]
    lines += ["", "## Validation checks", "", "| Check | Result | Detail |", "|---|---|---|"]
    lines += [f"| {r['check']} | {r['status']} | {r['detail']} |" for r in results]
    return "\n".join(lines) + "\n"


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    tables = {}
    for name, (build, _, _) in interim.TABLES.items():
        print(f"{name}", end=" ", flush=True)
        df = build().round(4)
        path = OUT_DIR / f"{name}.csv"
        df.to_csv(path, index=False)
        tables[name] = df
        print(f"{len(df):,} rows, {path.stat().st_size / 1e3:,.0f} KB")

    print("\nChecks")
    results = interim.checks()
    for r in results:
        print(f"  [{r['status']}] {r['check']}: {r['detail']}")
    (OUT_DIR / "README.md").write_text(readme(tables, results))
    print(f"\nWrote {len(tables)} tables and README.md to {OUT_DIR}")
    if any(r["status"] == "FAIL" for r in results):
        sys.exit(1)


if __name__ == "__main__":
    main()
